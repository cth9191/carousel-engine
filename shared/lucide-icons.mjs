/**
 * Writes a deck's cards/icons.js: the Lucide glyphs its pages use, inlined so they can take
 * currentColor (an <img> of an SVG can't), plus lucide() which swaps every <i data-lucide="name">
 * for its inline <svg>. Glyphs come from shared/vendor/lucide/ (lucide-static 0.460.0, ISC).
 *
 *   node shared/lucide-icons.mjs <out/icons.js> terminal copy check ...
 *   node shared/lucide-icons.mjs $D/cards/icons.js --from $D/cards
 *     (--from scans every *.html in that folder for data-lucide="…" and adds those names)
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const lucideDir = path.resolve(here, 'vendor/lucide');
const args = process.argv.slice(2);
const out = args.shift();
if (!out) { console.error('usage: lucide-icons.mjs <out/icons.js> [--from cardsDir] name ...'); process.exit(1); }
const names = new Set();
for (let i = 0; i < args.length; i++) {
  if (args[i] === '--from') {
    const dir = args[++i];
    for (const f of fs.readdirSync(dir).filter(f => f.endsWith('.html'))) {
      for (const m of fs.readFileSync(path.join(dir, f), 'utf8').matchAll(/data-lucide="([a-z0-9-]+)"/g)) names.add(m[1]);
    }
  } else names.add(args[i]);
}
const map = {};
for (const n of [...names].sort()) {
  const file = path.join(lucideDir, `${n}.svg`);
  if (!fs.existsSync(file)) { console.error(`no Lucide glyph "${n}" in ${lucideDir}`); process.exit(1); }
  map[n] = fs.readFileSync(file, 'utf8')
    .replace(/<!--[\s\S]*?-->/g, '')
    .replace(/\s*\n\s*/g, ' ')
    .replace(/\s+class="[^"]*"/, '')
    .replace(/\s+width="24"\s+height="24"/, '')
    .trim();
}
const js = `// Generated by shared/lucide-icons.mjs. Lucide (lucide-static 0.460.0), ISC licence.
window.LUCIDE = ${JSON.stringify(map, null, 1)};
window.lucide = function () {
  for (const el of document.querySelectorAll('i[data-lucide]')) {
    const svg = window.LUCIDE[el.dataset.lucide];
    if (!svg) throw new Error('icons.js has no glyph "' + el.dataset.lucide + '": rerun make-icons.mjs --from cards');
    const t = document.createElement('template');
    t.innerHTML = svg;
    const node = t.content.firstElementChild;
    node.setAttribute('class', ('lucide ' + el.className).trim());
    node.setAttribute('aria-hidden', 'true');
    el.replaceWith(node);
  }
};
`;
fs.mkdirSync(path.dirname(path.resolve(out)), { recursive: true });
fs.writeFileSync(out, js);
console.log(`${out}: ${Object.keys(map).length} glyphs (${Object.keys(map).join(', ')})`);
